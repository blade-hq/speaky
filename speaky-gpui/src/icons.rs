use gpui::{canvas, point, prelude::*, px, rgb, PathBuilder};

#[derive(Clone, Copy)]
pub enum Icon {
    Home,
    History,
    Terms,
    Settings,
    Play,
    Retry,
    Folder,
    Copy,
    Microphone,
    Stop,
    Guide,
    Model,
}

impl Icon {
    pub fn render(self, color: u32) -> impl IntoElement {
        let lines: &[&[(f32, f32)]] = match self {
            Self::Guide => &[
                &[
                    (8., 1.3),
                    (11.4, 2.2),
                    (13.8, 4.6),
                    (14.7, 8.),
                    (13.8, 11.4),
                    (11.4, 13.8),
                    (8., 14.7),
                    (4.6, 13.8),
                    (2.2, 11.4),
                    (1.3, 8.),
                    (2.2, 4.6),
                    (4.6, 2.2),
                    (8., 1.3),
                ],
                &[
                    (5.9, 5.5),
                    (6.8, 4.4),
                    (8.7, 4.4),
                    (10.1, 5.5),
                    (10.1, 6.7),
                    (8., 8.1),
                    (8., 9.3),
                ],
                &[(8., 11.6), (8., 12.)],
            ],
            Self::Model => &[
                &[(1.7, 5.2), (8., 1.7), (14.3, 5.2), (8., 8.7), (1.7, 5.2)],
                &[(1.7, 8.2), (8., 11.7), (14.3, 8.2)],
                &[(1.7, 11.2), (8., 14.7), (14.3, 11.2)],
            ],
            Self::Home => &[
                &[(1.5, 7.), (8., 1.5), (14.5, 7.)],
                &[(3., 6.), (3., 14.), (13., 14.), (13., 6.)],
                &[(6.5, 14.), (6.5, 9.5), (9.5, 9.5), (9.5, 14.)],
            ],
            Self::History => &[
                &[
                    (2., 5.5),
                    (4.5, 2.5),
                    (8., 1.5),
                    (11.5, 2.5),
                    (14., 5.5),
                    (14.5, 8.),
                    (14., 10.5),
                    (11.5, 13.5),
                    (8., 14.5),
                    (4.5, 13.5),
                    (2.5, 11.),
                ],
                &[(2., 2.5), (2., 5.5), (5., 5.5)],
                &[(8., 4.5), (8., 8.), (10.5, 9.5)],
            ],
            Self::Terms => &[
                &[
                    (4., 2.),
                    (13., 2.),
                    (13., 14.),
                    (4., 14.),
                    (2.5, 12.),
                    (2.5, 4.),
                    (4., 2.),
                ],
                &[(2.5, 12.), (4., 10.5), (13., 10.5)],
                &[(6., 5.), (10., 5.)],
                &[(6., 7.5), (9., 7.5)],
            ],
            Self::Settings => &[
                &[
                    (6.7, 1.4),
                    (9.3, 1.4),
                    (9.6, 3.),
                    (10.9, 3.7),
                    (12.4, 3.1),
                    (13.8, 5.2),
                    (12.8, 6.4),
                    (13., 8.),
                    (14.5, 8.8),
                    (13.9, 11.3),
                    (12.2, 11.2),
                    (11.1, 12.3),
                    (11., 13.9),
                    (8.5, 14.5),
                    (7.7, 13.1),
                    (6.2, 12.8),
                    (5., 13.8),
                    (2.9, 12.3),
                    (3.4, 10.8),
                    (2.7, 9.5),
                    (1.2, 9.1),
                    (1.2, 6.5),
                    (2.8, 6.2),
                    (3.5, 4.8),
                    (3., 3.3),
                    (5.2, 2.0),
                    (6.3, 3.),
                    (6.7, 1.4),
                ],
                &[
                    (10., 8.),
                    (9.4, 6.6),
                    (8., 6.),
                    (6.6, 6.6),
                    (6., 8.),
                    (6.6, 9.4),
                    (8., 10.),
                    (9.4, 9.4),
                    (10., 8.),
                ],
            ],
            Self::Play => &[&[(5., 2.5), (13., 8.), (5., 13.5), (5., 2.5)]],
            Self::Retry => &[
                &[
                    (13.5, 5.),
                    (11., 2.5),
                    (7., 2.),
                    (3.5, 4.),
                    (2., 7.5),
                    (3., 11.),
                    (6., 13.5),
                    (10., 13.5),
                    (13., 11.),
                ],
                &[(10., 5.), (13.5, 5.), (13.5, 1.5)],
            ],
            Self::Folder => &[&[
                (1.5, 13.),
                (1.5, 3.5),
                (6.5, 3.5),
                (8.5, 5.5),
                (14.5, 5.5),
                (14.5, 13.),
                (1.5, 13.),
            ]],
            Self::Copy => &[
                &[(5., 5.), (14., 5.), (14., 14.), (5., 14.), (5., 5.)],
                &[(2., 10.), (2., 2.), (10., 2.)],
            ],
            Self::Microphone => &[
                &[
                    (6., 3.),
                    (7., 1.5),
                    (9., 1.5),
                    (10., 3.),
                    (10., 7.),
                    (9., 8.5),
                    (7., 8.5),
                    (6., 7.),
                    (6., 3.),
                ],
                &[
                    (3.5, 6.5),
                    (3.5, 8.),
                    (5., 10.5),
                    (8., 11.5),
                    (11., 10.5),
                    (12.5, 8.),
                    (12.5, 6.5),
                ],
                &[(8., 11.5), (8., 14.5)],
                &[(5.5, 14.5), (10.5, 14.5)],
            ],
            Self::Stop => &[&[(4., 4.), (12., 4.), (12., 12.), (4., 12.), (4., 4.)]],
        };
        canvas(
            |_, _, _| (),
            move |bounds, _, window, _| {
                let mut path = PathBuilder::stroke(px(1.3));
                for line in lines {
                    let (start_x, start_y) = line[0];
                    path.move_to(bounds.origin + point(px(start_x), px(start_y)));
                    for &(end_x, end_y) in &line[1..] {
                        path.line_to(bounds.origin + point(px(end_x), px(end_y)));
                    }
                }
                if let Ok(path) = path.build() {
                    window.paint_path(path, rgb(color));
                }
            },
        )
        .size(px(16.))
        .flex_none()
    }
}
